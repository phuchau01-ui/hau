-- Run this script in Supabase > SQL Editor.
create table if not exists public.survey_responses (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  identity text not null,
  respondent_name text,
  nationality text,
  age text not null,
  visit text not null,
  affinity text not null,
  first_impression jsonb not null default '[]'::jsonb,
  attractions jsonb not null default '[]'::jsonb,
  likert jsonb not null default '[]'::jsonb,
  sources jsonb not null default '[]'::jsonb,
  cities jsonb not null default '[]'::jsonb,
  intention text not null,
  comments text,
  feedback text
);
alter table public.survey_responses enable row level security;
-- Public visitors may submit a response, but cannot read or modify any response.
drop policy if exists "Anyone can submit survey" on public.survey_responses;
create policy "Anyone can submit survey" on public.survey_responses
for insert to anon, authenticated with check (true);
-- Replace admin@example.com with the email of your administrator account.
drop policy if exists "Only admin can read survey" on public.survey_responses;
create policy "Only admin can read survey" on public.survey_responses
for select to authenticated
using ((auth.jwt() ->> 'email') = 'admin@example.com');
